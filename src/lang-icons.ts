// Shown for languages without a brand icon, e.g. plain text or niche grammars
const GENERIC_PATH =
  "M8.7 7.3 4 12l4.7 4.7 1.4-1.4L6.8 12l3.3-3.3zm6.6 0-1.4 1.4 3.3 3.3-3.3 3.3 1.4 1.4L20 12z";

// Aliases that share a grammar but deserve their own mark (hljs highlights html as xml, tsx as ts)
const ALIAS_OVERRIDES: Record<string, SimpleIcon> = { html: siHtml5, tsx: siReact, jsx: siReact };

export function langIcon(alias: string | undefined, id: string | undefined): string {
  const icon =
    (alias ? ALIAS_OVERRIDES[alias.toLowerCase()] : undefined) ?? (id ? ICONS[id] : undefined);
  const path = icon?.path ?? GENERIC_PATH;
  return `<svg class="code-icon" viewBox="0 0 24 24" aria-hidden="true"><path d="${path}"/></svg>`;
}
